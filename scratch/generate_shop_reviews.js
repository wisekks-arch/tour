// Generate 20 reviews for each product
function buildProductsData(originalProducts) {
  return originalProducts.map((p, pIdx) => {
    const templates = productReviewsTemplates[p.id] || [];
    const reviews = [];

    for (let i = 0; i < 20; i++) {
      const revId = `rev-${p.id}-${i + 1}`;
      const author = getRandomAuthor(pIdx * 20 + i + 1);
      const rating = (i % 7 === 0) ? 4 : 5; // 대부분 5점, 가끔 4점
      const dayOffset = (i * 3 + (pIdx % 5)) % 60;
      const d = new Date(2026, 8, 30); // 2026-09-30 기준
      d.setDate(d.getDate() - dayOffset);
      const dateStr = d.toISOString().slice(0, 10);
      const content = templates[i] || `${p.name} 정말 만족스러운 구매였습니다. 품질과 배송 모두 최고예요!`;
      const likes = Math.floor((20 - i) * 1.5 + (pIdx % 5) * 2) + 2;

      reviews.push({
        id: revId,
        author: author,
        rating: rating,
        date: dateStr,
        content: content,
        likes: likes
      });
    }

    const totalRatings = reviews.reduce((sum, r) => sum + r.rating, 0);
    const avgRating = Number((totalRatings / reviews.length).toFixed(1));

    return {
      ...p,
      rating: avgRating,
      reviewCount: reviews.length,
      reviews: reviews
    };
  });
}

// 1. Read existing gen_data.ps1
const genDataPath = path.join(__dirname, '..', 'gen_data.ps1');
let content = fs.readFileSync(genDataPath, 'utf8');

// Extract productsJson string
const startMarker = '$productsJson = @\'\r\n';
const altStartMarker = '$productsJson = @\'\n';
const actualStart = content.includes(startMarker) ? startMarker : altStartMarker;
const endMarker = '\'@\r\n\r\n[System.IO.File]::WriteAllText((Join-Path $dataDir \'products.json\'';
const altEndMarker = '\'@\n\n[System.IO.File]::WriteAllText((Join-Path $dataDir \'products.json\'';
const actualEnd = content.includes(endMarker) ? endMarker : altEndMarker;

const startIndex = content.indexOf(actualStart);
const endIndex = content.indexOf(actualEnd);

if (startIndex === -1 || endIndex === -1) {
  console.error('Could not find productsJson markers in gen_data.ps1');
  process.exit(1);
}

const rawProductsJson = content.slice(startIndex + actualStart.length, endIndex);
let products;
try {
  products = JSON.parse(rawProductsJson);
} catch (e) {
  console.error('Failed to parse productsJson:', e);
  process.exit(1);
}

console.log(`Loaded ${products.length} products from gen_data.ps1`);

const updatedProducts = buildProductsData(products);
console.log(`Generated 20 reviews for each of ${updatedProducts.length} products (Total: ${updatedProducts.length * 20} reviews)`);

const newProductsJsonStr = JSON.stringify(updatedProducts, null, 2);

const newGenDataContent = content.slice(0, startIndex + actualStart.length) + newProductsJsonStr + '\r\n' + content.slice(endIndex);

fs.writeFileSync(genDataPath, newGenDataContent, 'utf8');
console.log('Successfully updated gen_data.ps1 with 240 reviews!');
